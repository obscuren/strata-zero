"""python3 export.py <flavor/implant_art.ron> — writes every chrome piece's card art for the game.

Each drawing becomes rows of one char per pixel (empty is `.`) and a colour for each char,
as the skill cards' hardware art does. No labels, no neon.
"""

import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import implantart as ia  # noqa: E402

CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"


def rgb(c):
    return "(%d, %d, %d)" % tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))


def entry(key):
    grid = ia.ART[key]()
    chars, rows = {}, []
    for y in range(ia.H):
        row = ""
        for x in range(ia.W):
            c = grid[y][x]
            if c is None:
                row += "."
                continue
            if c not in chars:
                chars[c] = CHARS[len(chars)]
            row += chars[c]
        rows.append(row)
    colours = ", ".join("'%s': %s" % (ch, rgb(c)) for c, ch in chars.items())
    body = "\n".join('            "%s",' % r for r in rows)
    return ('    "%s": (\n        rows: [\n%s\n        ],\n        colours: {%s},\n    ),\n'
            % (key, body, colours))


def export():
    out = ["// Every piece of chrome's card art, 30x12 pixels. Generated by\n"
           "// docs/superpowers/specs/2026-10-29-stats-chrome-art/export.py: draw there, not here.\n"
           "{\n"]
    out += [entry(k) for k in ia.ART]
    out.append("}\n")
    return "".join(out)


if __name__ == "__main__":
    ia.check()
    open(sys.argv[1], "w").write(export())
