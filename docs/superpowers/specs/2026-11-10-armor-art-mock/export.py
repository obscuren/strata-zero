"""python3 -I export.py <flavor/item_art.ron> — writes every item's picture for the game.

Each drawing becomes rows of one char per pixel (empty is `.`), a colour for each char,
and the labels laid over its cells. The drawings themselves live in gen.py.
"""

import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen  # noqa: E402

CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

# Item id to its drawing, in the order the file lists them.
PICTURES = [
    ("salvage_jacket", gen.concept_d),
    ("ballistic_weave", gen.ballistic_weave),
    ("cargo_pants", gen.cargo_pants),
    ("hardhat", gen.hardhat),
    ("mirrorshades", gen.mirrorshades),
]


def rgb(c):
    return "(%d, %d, %d)" % tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))


def entry(key, c):
    chars, rows = {}, []
    for y in range(c.h):
        row = ""
        for x in range(c.w):
            col = c.p[y][x]
            if col is None:
                row += "."
                continue
            if col not in chars:
                if len(chars) == len(CHARS):
                    sys.exit("%s: more than %d colours" % (key, len(CHARS)))
                chars[col] = CHARS[len(chars)]
            row += chars[col]
        rows.append(row)
    colours = ", ".join("'%s': %s" % (ch, rgb(col)) for col, ch in chars.items())
    body = "\n".join('            "%s",' % r for r in rows)
    labels = "".join(
        '\n            (x: %d, y: %d, text: "%s", colour: %s),' % (x, y, text, rgb(fg))
        for x, y, text, fg, _bold in c.labels)
    labels = "[%s\n        ]" % labels if labels else "[]"
    return ('    "%s": (\n        rows: [\n%s\n        ],\n        colours: {%s},\n'
            '        labels: %s,\n    ),\n' % (key, body, colours, labels))


def main():
    out = sys.argv[1]
    text = ("// Every item's picture: what an item with no look of its own shows on its\n"
            "// blueprint. Generated by docs/superpowers/specs/2026-11-10-armor-art-mock/"
            "export.py:\n// draw there, not here.\n{\n")
    for key, draw in PICTURES:
        c = draw()
        if c.h % 2:
            sys.exit("%s: an odd number of rows" % key)
        text += entry(key, c)
    text += "}\n"
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
