"""python3 export.py <flavor/skill_art.ron> — writes every skill's art for the game.

Hardware becomes rows of one char per pixel with a colour for each char (the panel colour,
used as a hole, is `.`), and its labels. A neon sign becomes rows of `#` (a tube in the
skill's stat colour), `+` (a tube in the accent) and `.` (the plate), and its accent.
"""

import sys
import skillart as sa

CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"


def rgb(c):
    return "(%d, %d, %d)" % sa.hexrgb(c)


def hardware(skill):
    p = sa.drawn(skill)
    chars, rows = {}, []
    for y in range(sa.H):
        row = ""
        for x in range(sa.W):
            c = p.p[y][x]
            if c is None or c == sa.PANEL:
                row += "."
                continue
            if c not in chars:
                chars[c] = CHARS[len(chars)]
            row += chars[c]
        rows.append(row)
    colours = ", ".join("'%s': %s" % (ch, rgb(c)) for c, ch in chars.items())
    labels = ", ".join('(%d, %d, "%s", %s, %s)' % (cx, cy, s, rgb(ink), rgb(ground))
                       for cx, cy, s, ink, ground in p.text)
    body = "\n".join('            "%s",' % r for r in rows)
    return ("    \"%s\": Hardware(\n        rows: [\n%s\n        ],\n        colours: {%s},\n"
            "        labels: [%s],\n    ),\n" % (skill, body, colours, labels))


def neon(skill):
    tubes = sa.sign(skill)
    rows = []
    for y in range(sa.H):
        rows.append("".join("." if (x, y) not in tubes else ("+" if tubes[(x, y)] else "#")
                            for x in range(sa.W)))
    body = "\n".join('            "%s",' % r for r in rows)
    return ("    \"%s\": Neon(\n        rows: [\n%s\n        ],\n        accent: %s,\n    ),\n"
            % (skill, body, rgb(sa.NEON[skill][2])))


def entry(name):
    """One drawing in its section, indented a level."""
    text = neon(name) if name in sa.NEON else hardware(name)
    return "".join("    " + line + "\n" for line in text.splitlines())


def export():
    out = ["// Every skill's and category's card art, 34x20 pixels. Generated by\n"
           "// docs/superpowers/specs/2026-10-23-skill-cards-art/export.py: draw there, not here.\n"
           "(\n    skills: {\n"]
    for _, skills in sa.ORDER:
        out += [entry(s) for s in skills]
    out.append("    },\n    categories: {\n")
    out += [entry(c) for c in sa.CATEGORIES]
    out.append("    },\n)\n")
    return "".join(out)


if __name__ == "__main__":
    open(sys.argv[1], "w").write(export())
